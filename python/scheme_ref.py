#!/usr/bin/env python3
"""Independent reference implementation of Concertina.

It uses only the Python standard library (hashlib, hmac) and the
`cryptography` package for single-block AES, and generates the known-answer
tests in ../src/kat_generated.h, which the C self-test verifies.

    python3 scheme_ref.py            # regenerate ../src/kat_generated.h

Encoding (see the header of src/scheme.h):
    X_P = H(Pbar || 0x02 || T),  X_C = H(Cbar || 0x01 || T),
    counter block i = E(S xor <i>_128), i = 0, 1, ...
"""
import hashlib
import hmac
import os
import random
import sys

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

SCHEME_NAME = b"concertina"  # prefix of the KDF labels, as in the paper
HASHES = {"sha3": hashlib.sha3_256, "sha256": hashlib.sha256}


def aes_ecb(key, block):
    enc = Cipher(algorithms.AES(key), modes.ECB()).encryptor()
    return enc.update(block) + enc.finalize()


def xor(a, b):
    return bytes(x ^ y for x, y in zip(a, b))


def H(hname, key, msg):
    return hmac.new(key, msg, HASHES[hname]).digest()


def derive(hname, km):
    k = len(km)
    out = {}
    for u in ["1", "2", "3", "4", "ctr", "hash"]:
        msg = (1).to_bytes(4, "big") + SCHEME_NAME + b"/" + u.encode() + b"\x00" \
            + (8 * k).to_bytes(4, "big")
        out[u] = H(hname, km, msg)[:k]
    return out


def ctr(kctr, S, data):
    out = bytearray()
    s = int.from_bytes(S, "big")
    for i in range((len(data) + 15) // 16):
        ks = aes_ecb(kctr, (s ^ i).to_bytes(16, "big"))
        blk = data[16 * i:16 * i + 16]
        out += xor(blk, ks[:len(blk)])
    return bytes(out)


def encrypt(hname, km, tweak, P):
    assert len(P) >= 32 and len(tweak) == 16
    K = derive(hname, km)
    E = lambda u, x: aes_ecb(K[u], x)
    P1, P2, Pb = P[:16], P[16:32], P[32:]
    X = H(hname, K["hash"], Pb + b"\x02" + tweak)
    U1, U2 = xor(P1, X[:16]), xor(P2, X[16:])
    R = xor(U2, E("1", U1))
    L = xor(U1, E("2", R))
    V2 = xor(R, E("3", L))
    V1 = xor(L, E("4", V2))
    S = xor(xor(U1, U2), xor(V1, V2))
    Cb = ctr(K["ctr"], S, Pb)
    Y = H(hname, K["hash"], Cb + b"\x01" + tweak)
    return xor(V1, Y[:16]) + xor(V2, Y[16:]) + Cb


def decrypt(hname, km, tweak, C):
    K = derive(hname, km)
    E = lambda u, x: aes_ecb(K[u], x)
    C1, C2, Cb = C[:16], C[16:32], C[32:]
    Y = H(hname, K["hash"], Cb + b"\x01" + tweak)
    V1, V2 = xor(C1, Y[:16]), xor(C2, Y[16:])
    L = xor(V1, E("4", V2))
    R = xor(V2, E("3", L))
    U1 = xor(L, E("2", R))
    U2 = xor(R, E("1", U1))
    S = xor(xor(U1, U2), xor(V1, V2))
    Pb = ctr(K["ctr"], S, Cb)
    X = H(hname, K["hash"], Pb + b"\x02" + tweak)
    return xor(U1, X[:16]) + xor(U2, X[16:]) + Pb


def xts_encrypt(key, iv, data):
    enc = Cipher(algorithms.AES(key), modes.XTS(iv)).encryptor()
    return enc.update(data) + enc.finalize()


def c_bytes(b):
    if not b:
        return '""'
    s = "".join(f"\\x{x:02x}" for x in b)
    return "\n\t\t\"" + "\"\n\t\t\"".join(s[i:i + 64] for i in range(0, len(s), 64)) + "\""


def main():
    rnd = random.Random(20260926)
    rb = lambda n: bytes(rnd.getrandbits(8) for _ in range(n))
    lines = ["/* GENERATED by python/scheme_ref.py -- do not edit. */",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]

    # ---- scheme ----
    lines += ["struct kat_scheme { int hash; size_t key_len; const uint8_t *key;",
              "\tconst uint8_t *tweak; size_t len; const uint8_t *pt; const uint8_t *ct; };",
              "static const struct kat_scheme kat_scheme[] = {"]
    count = 0
    for hname, hid in (("sha3", 0), ("sha256", 1)):
        for klen in (16, 24, 32):
            for ln in (32, 33, 47, 48, 49, 63, 64, 100, 167, 168, 169, 255, 256, 511, 1000):
                km, tw, pt = rb(klen), rb(16), rb(ln)
                ct = encrypt(hname, km, tw, pt)
                assert decrypt(hname, km, tw, ct) == pt
                lines.append(f"\t{{{hid}, {klen}, (const uint8_t *){c_bytes(km)},\n\t (const uint8_t *){c_bytes(tw)}, {ln},"
                             f"\n\t (const uint8_t *){c_bytes(pt)},\n\t (const uint8_t *){c_bytes(ct)}}},")
                count += 1
    lines += ["};", f"#define KAT_SCHEME_COUNT {count}", ""]

    # ---- hashes and HMACs ----
    lines += ["struct kat_mac { int hash; size_t key_len; const uint8_t *key;",
              "\tsize_t len; const uint8_t *msg; const uint8_t *mac; const uint8_t *digest; };",
              "static const struct kat_mac kat_mac[] = {"]
    count = 0
    for hname, hid in (("sha3", 0), ("sha256", 1)):
        for klen in (16, 32, 200):
            for ln in (0, 1, 17, 55, 56, 63, 64, 65, 119, 135, 136, 137, 152, 300, 1000):
                key, msg = rb(klen), rb(ln)
                mac = H(hname, key, msg)
                dig = HASHES[hname](msg).digest()
                lines.append(f"\t{{{hid}, {klen}, (const uint8_t *){c_bytes(key)}, {ln},"
                             f"\n\t (const uint8_t *){c_bytes(msg)},\n\t (const uint8_t *){c_bytes(mac)},"
                             f"\n\t (const uint8_t *){c_bytes(dig)}}},")
                count += 1
    lines += ["};", f"#define KAT_MAC_COUNT {count}", ""]

    # ---- XTS ----
    lines += ["struct kat_xts { size_t key_len; const uint8_t *key; const uint8_t *iv;",
              "\tsize_t len; const uint8_t *pt; const uint8_t *ct; };",
              "static const struct kat_xts kat_xts[] = {"]
    count = 0
    for klen in (32, 64):
        for ln in (16, 32, 48, 128, 144, 512, 4096):
            key = rb(klen // 2) + rb(klen // 2)
            iv, pt = rb(16), rb(ln)
            ct = xts_encrypt(key, iv, pt)
            lines.append(f"\t{{{klen}, (const uint8_t *){c_bytes(key)},\n\t (const uint8_t *){c_bytes(iv)}, {ln},"
                         f"\n\t (const uint8_t *){c_bytes(pt)},\n\t (const uint8_t *){c_bytes(ct)}}},")
            count += 1
    lines += ["};", f"#define KAT_XTS_COUNT {count}", ""]

    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "kat_generated.h")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.normpath(path)}")


if __name__ == "__main__":
    sys.exit(main())
