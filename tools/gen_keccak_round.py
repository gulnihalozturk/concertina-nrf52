#!/usr/bin/env python3
"""Generates the fully unrolled Keccak-f[1600] round bodies used in src/keccak.c.

Two variants are produced from the same schedule:
  * KECCAK_ROUND_SCALAR: 64-bit general-purpose registers,
  * KECCAK_ROUND_CE:     ARMv8.2-SHA3 instructions (EOR3, RAX1, XAR, BCAX).
The rho and pi steps are performed in place along the pi cycle, and theta's
D-values are folded into the rotations, so that only a handful of temporaries
are live at any time.
"""
PILN = [10, 7, 11, 17, 18, 3, 5, 16, 8, 21, 24, 4, 15, 23, 19, 13, 12, 2, 20, 14, 22, 9, 6, 1]
ROTC = [1, 3, 6, 10, 15, 21, 28, 36, 45, 55, 2, 14, 27, 41, 56, 8, 25, 43, 62, 18, 39, 61, 20, 44]

def gen(kind):
    L = []
    ce = kind == "CE"
    for x in range(5):
        if ce:
            L.append(f"C{x} = veor3q_u64(veor3q_u64(A{x}, A{x+5}, A{x+10}), A{x+15}, A{x+20});")
        else:
            L.append(f"C{x} = A{x} ^ A{x+5} ^ A{x+10} ^ A{x+15} ^ A{x+20};")
    for x in range(5):
        a, b = (x + 4) % 5, (x + 1) % 5
        L.append(f"D{x} = vrax1q_u64(C{a}, C{b});" if ce else f"D{x} = C{a} ^ ROL64(C{b}, 1);")
    L.append("A0 = veorq_u64(A0, D0);" if ce else "A0 ^= D0;")
    L.append("T = A1;")
    src = 1
    for i, j in enumerate(PILN):
        r = ROTC[i]
        L.append(f"BC = A{j};")
        if ce:
            L.append(f"A{j} = vxarq_u64(T, D{src % 5}, {(64 - r) % 64});")
        else:
            L.append(f"A{j} = ROL64(T ^ D{src % 5}, {r});")
        L.append("T = BC;")
        src = j
    for y in range(5):
        v = [f"A{5*y + x}" for x in range(5)]
        L.append(f"T = {v[0]}; BC = {v[1]};")
        seq = [(0, 2, 1), (1, 3, 2), (2, 4, 3), (3, "T", 4), (4, "BC", "T")]
        for x, b, c in seq:
            bb = b if isinstance(b, str) else v[b]
            cc = c if isinstance(c, str) else v[c]
            if ce:
                L.append(f"{v[x]} = vbcaxq_u64({v[x]}, {bb}, {cc});")
            else:
                L.append(f"{v[x]} ^= (~{cc}) & {bb};")
    L.append("A0 = veorq_u64(A0, vdupq_n_u64(RC));" if ce else "A0 ^= RC;")
    return L

with open("src/keccak_round.inc", "w") as f:
    f.write("/* GENERATED by tools/gen_keccak_round.py -- do not edit. */\n")
    for kind in ("SCALAR", "CE"):
        f.write(f"#define KECCAK_ROUND_{kind}(RC) do {{ \\\n")
        for line in gen(kind):
            f.write(f"\t{line} \\\n")
        f.write("} while (0)\n\n")
print("src/keccak_round.inc written")
