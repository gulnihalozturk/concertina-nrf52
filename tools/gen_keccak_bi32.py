#!/usr/bin/env python3
"""Generates src/keccak_bi32.inc: one Keccak-f[1600] round on the
bit-interleaved 32-bit representation (for 32-bit cores such as Cortex-M4).

Each 64-bit lane L of the state is stored as two 32-bit words: E holds the
even-indexed bits of L and O the odd-indexed bits (word 2*i and 2*i+1 for
lane i = x + 5*y). A 64-bit rotation then becomes two 32-bit rotations:
    ROL64(L, 2k)   -> E' = ROL32(E, k),   O' = ROL32(O, k)
    ROL64(L, 2k+1) -> E' = ROL32(O, k+1), O' = ROL32(E, k)
The rotation offsets and round constants are derived here from the FIPS 202
definitions rather than typed in by hand.

    python3 tools/gen_keccak_bi32.py     # rewrites src/keccak_bi32.inc
"""
import os


def rho_offsets():
    r = {(0, 0): 0}
    x, y = 1, 0
    for t in range(24):
        r[(x, y)] = ((t + 1) * (t + 2) // 2) % 64
        x, y = y, (2 * x + 3 * y) % 5
    return r


def round_constants():
    def rc_bit(t):
        if t % 255 == 0:
            return 1
        R = 1
        for _ in range(t % 255):
            R <<= 1
            if R & 0x100:
                R ^= 0x171
        return R & 1

    out = []
    for ir in range(24):
        rc = 0
        for j in range(7):
            if rc_bit(j + 7 * ir):
                rc |= 1 << ((1 << j) - 1)
        out.append(rc)
    return out


def split(v):
    e = o = 0
    for i in range(32):
        e |= ((v >> (2 * i)) & 1) << i
        o |= ((v >> (2 * i + 1)) & 1) << i
    return e, o


def rol(expr, k):
    k %= 32
    return expr if k == 0 else f"ROL32({expr}, {k})"


def main():
    r = rho_offsets()
    rc = round_constants()
    assert rc[0] == 1 and rc[1] == 0x8082 and rc[23] == 0x8000000080008008
    L = []
    L.append("/* GENERATED by tools/gen_keccak_bi32.py -- do not edit. */")
    L.append("/* Round constants, bit-interleaved: {even word, odd word}. */")
    L.append("static const u32 KECCAK_RC_BI[24][2] = {")
    for v in rc:
        e, o = split(v)
        L.append(f"\t{{0x{e:08x}u, 0x{o:08x}u}}, /* 0x{v:016x} */")
    L.append("};")
    L.append("")
    L.append("/* out = Round(in) with round constant {rce, rco}. in != out. */")
    L.append("static inline __attribute__((always_inline)) void keccak_round_bi32("
             "u32 *restrict out, const u32 *restrict in, u32 rce, u32 rco)")
    L.append("{")
    L.append("\tu32 Ce0, Co0, Ce1, Co1, Ce2, Co2, Ce3, Co3, Ce4, Co4;")
    L.append("\tu32 De0, Do0, De1, Do1, De2, Do2, De3, Do3, De4, Do4;")
    L.append("\tu32 Be0, Bo0, Be1, Bo1, Be2, Bo2, Be3, Bo3, Be4, Bo4;")
    # theta: column parities
    for x in range(5):
        for h, off in (("e", 0), ("o", 1)):
            terms = " ^ ".join(f"in[{2 * (x + 5 * y) + off}]" for y in range(5))
            L.append(f"\tC{h}{x} = {terms};")
    # D[x] = C[x-1] ^ ROL64(C[x+1], 1)
    for x in range(5):
        xm, xp = (x - 1) % 5, (x + 1) % 5
        L.append(f"\tDe{x} = Ce{xm} ^ ROL32(Co{xp}, 1);")
        L.append(f"\tDo{x} = Co{xm} ^ Ce{xp};")
    # rho + pi + chi (+ iota), one output plane Y at a time
    for Y in range(5):
        for X in range(5):
            ysrc = X
            xsrc = (3 * (Y - 3 * X)) % 5
            assert (2 * xsrc + 3 * ysrc) % 5 == Y
            lane = xsrc + 5 * ysrc
            rr = r[(xsrc, ysrc)]
            ae = f"(in[{2 * lane}] ^ De{xsrc})"
            ao = f"(in[{2 * lane + 1}] ^ Do{xsrc})"
            if rr % 2 == 0:
                k = rr // 2
                L.append(f"\tBe{X} = {rol(ae, k)};")
                L.append(f"\tBo{X} = {rol(ao, k)};")
            else:
                k = rr // 2
                L.append(f"\tBe{X} = {rol(ao, k + 1)};")
                L.append(f"\tBo{X} = {rol(ae, k)};")
        for X in range(5):
            X1, X2 = (X + 1) % 5, (X + 2) % 5
            idx = 2 * (X + 5 * Y)
            for h, off in (("e", 0), ("o", 1)):
                expr = f"B{h}{X} ^ (~B{h}{X1} & B{h}{X2})"
                if X == 0 and Y == 0:
                    expr = f"({expr}) ^ rc{h}"
                L.append(f"\tout[{idx + off}] = {expr};")
    L.append("}")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src",
                        "keccak_bi32.inc")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {os.path.normpath(path)}")


if __name__ == "__main__":
    main()
