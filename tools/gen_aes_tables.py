#!/usr/bin/env python3
"""Generates src/aes_tables.inc: the AES tables as constants, for builds with
AES_TABLES_IN_FLASH=1 (by default the tables are built in RAM at first use,
because flash data reads are slower; the constants trade that speed for RAM).
Same contents as build_table() in src/aes.c and build_tables() in
src/aes_dec.c, computed here from the definitions in FIPS 197."""
import os


def xtime(x):
    return ((x << 1) ^ (0x1b if x & 0x80 else 0)) & 0xff


def gmul(x, c):
    r = 0
    while c:
        if c & 1:
            r ^= x
        x = xtime(x)
        c >>= 1
    return r


def inv(x):
    return 0 if x == 0 else next(y for y in range(1, 256) if gmul(x, y) == 1)


def rotl8(x, s):
    return ((x << s) | (x >> (8 - s))) & 0xff


sbox = []
for x in range(256):
    b = inv(x)
    sbox.append(b ^ rotl8(b, 1) ^ rotl8(b, 2) ^ rotl8(b, 3) ^ rotl8(b, 4) ^ 0x63)
inv_sbox = [0] * 256
for x, s in enumerate(sbox):
    inv_sbox[s] = x
assert sbox[0] == 0x63 and sbox[1] == 0x7c and inv_sbox[0x63] == 0
te = [xtime(s) | (s << 8) | (s << 16) | ((xtime(s) ^ s) << 24) for s in sbox]
td = [gmul(s, 14) | (gmul(s, 9) << 8) | (gmul(s, 13) << 16) | (gmul(s, 11) << 24)
      for s in inv_sbox]


def arr(decl, vals, fmt, per):
    lines = [decl + " = {"]
    for i in range(0, len(vals), per):
        lines.append("\t" + ", ".join(fmt % v for v in vals[i:i + per]) + ",")
    return "\n".join(lines) + "\n};\n"


out = ["/* GENERATED by tools/gen_aes_tables.py: AES tables as constants (FIPS 197). */",
       "#ifdef AES_TABLES_WANT_TE",
       arr("static const u32 Te[256]", te, "0x%08xu", 6) + "#endif",
       "#ifdef AES_TABLES_WANT_SB",
       arr("static const u8 Sb[256]", sbox, "0x%02x", 12) + "#endif",
       "#ifdef AES_TABLES_WANT_TD",
       arr("static const u32 Td[256]", td, "0x%08xu", 6)
       + arr("static const u8 inv_sbox[256]", inv_sbox, "0x%02x", 12) + "#endif", ""]
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "aes_tables.inc")
with open(path, "w") as f:
    f.write("\n".join(out))
print("wrote", os.path.normpath(path))
